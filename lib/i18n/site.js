// t("clé du site") ou t("Texte français du dashboard") ; t("Bonjour {nom}", { nom }) remplace {nom}.
export function createT(lang) {
  const en = lang === "en";
  const dict = en ? EN : FR;
  return function t(key, vars) {
    let s = dict[key] ?? (en ? DASH_EN[key] : undefined) ?? FR[key] ?? key;
    if (vars) for (const k of Object.keys(vars)) s = s.split("{" + k + "}").join(String(vars[k]));
    return s;
  };
}
