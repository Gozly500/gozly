// Langue par défaut d'un nouveau visiteur : français, sauf si son navigateur ne
// demande aucune variante du français et préfère l'anglais.
export function langDepuisAcceptLanguage(header) {
  const h = (header || "").toLowerCase();
  if (/\bfr\b|fr-/.test(h)) return "fr";
  if (/^\s*en\b/.test(h)) return "en";
  return "fr";
}

