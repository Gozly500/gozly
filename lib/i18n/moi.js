export function traduire(langue, cle, params) {
  let texte = DICT[langue]?.[cle] ?? DICT.fr[cle] ?? cle;
  if (params) {
    for (const [k, v] of Object.entries(params)) {
      texte = texte.replaceAll(`{${k}}`, v);
    }
  }
  return texte;
}

export function localeDate(langue) {
  return langue === "en" ? "en-CA" : "fr-CA";
}
